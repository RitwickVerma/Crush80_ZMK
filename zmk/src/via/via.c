/*
 * VIA support: lets the VIA configurator (usevia.app) edit the keymap over
 * USB. A third raw HID interface (HID_2, usage page 0xFF60 / usage 0x61, 32
 * byte reports, interface number 2) speaks the VIA protocol, version 12 (the
 * one with QMK's current keycode numbering and v3 keyboard definitions).
 * OpenRGB keeps its own interface (HID_1): its command numbers collide with
 * VIA's, so the two cannot share one.
 *
 * The keymap shown to VIA is ZMK's live keymap, the one ZMK Studio edits:
 * bindings are translated to and from QMK keycodes (via_xlat.c) and written
 * with zmk_keymap_set_layer_binding_at_idx(), so changes survive reboots and
 * show up in Studio. Behaviors VIA cannot express appear as a read-only
 * placeholder key and are never overwritten unless the user sets that key.
 *
 * Supported: keymap read/write, layers, the key tester. Not supported (the
 * app hides or greys them): macros, lighting menus, encoders.
 *
 * The definition VIA needs (config/via.json) is loaded by the user in VIA's
 * Design tab; it is generated by scripts/gen_via_def.py.
 */

