#!/usr/bin/env python3
"""Generate the VIA keyboard definition from the board's devicetree.

Reads the matrix transform and physical layout in zmk/boards/crush80/crush80.dts
and the custom keycodes in zmk/src/via/custom_keycodes.def, and writes:

  config/via.json           v3 definition to load in VIA's Design tab
  zmk/src/via/via_def.h     matrix size, checked against the board at build time

Output is deterministic, so build.sh runs this on every build and git shows
nothing unless the layout changed.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DTS = ROOT / "zmk/boards/crush80/crush80.dts"
CUSTOM = ROOT / "zmk/src/via/custom_keycodes.def"
OUT_JSON = ROOT / "config/via.json"
OUT_HDR = ROOT / "zmk/src/via/via_def.h"


def parse_dts(text):
    m = re.search(r"default_transform:.*?map = <(.*?)>;", text, re.S)
    cells = [(int(r), int(c)) for r, c in re.findall(r"RC\((\d+),(\d+)\)", m.group(1))]
    keys = re.findall(r"<&key_physical_attrs\s+(\d+)\s+(\d+)\s+(\d+)\s+(\d+)\s+\d+\s+\d+\s+\d+>", text)
    if len(cells) != len(keys):
        sys.exit(f"{DTS}: {len(cells)} matrix cells but {len(keys)} physical keys")
    rows = int(re.search(r"default_transform:.*?rows = <(\d+)>", text, re.S).group(1))
    cols = int(re.search(r"default_transform:.*?columns = <(\d+)>", text, re.S).group(1))
    return cells, [tuple(int(v) for v in k) for k in keys], rows, cols


def kle_rows(cells, keys):
    """Keyboard Layout Editor rows; each key's legend is its "row,col" matrix cell."""
    by_y = {}
    for (r, c), (w, h, x, y) in zip(cells, keys):
        by_y.setdefault(y, []).append((x, w, f"{r},{c}"))
    out, prev_y = [], None
    for y in sorted(by_y):
        row, cursor = [], 0.0
        for x, w, label in sorted(by_y[y]):
            props = {}
            if prev_y is not None and not row:
                gap = (y - prev_y) / 100.0 - 1.0  # KLE advances one unit per row
                if gap:
                    props["y"] = round(gap, 2)
            if x / 100.0 != cursor:
                props["x"] = round(x / 100.0 - cursor, 2)
            if w != 100:
                props["w"] = w / 100.0
            if props:
                row.append(props)
            row.append(label)
            cursor = x / 100.0 + w / 100.0
        out.append(row)
        prev_y = y
    return out


def custom_keycodes():
    items = re.findall(r'VK_CUSTOM\("([^"]*)",\s*"([^"]*)"', CUSTOM.read_text())
    if not 0 < len(items) <= 256:
        sys.exit("custom_keycodes.def: need 1-256 entries")
    return [{"name": n, "title": t, "shortName": n} for n, t in items]


def main():
    cells, keys, rows, cols = parse_dts(DTS.read_text())
    definition = {
        "name": "Wobkey Crush 80",
        "vendorId": "0x1D50",
        "productId": "0x615E",
        "matrix": {"rows": rows, "cols": cols},
        "menus": [],
        "customKeycodes": custom_keycodes(),
        "layouts": {"keymap": kle_rows(cells, keys)},
    }
    OUT_JSON.write_text(json.dumps(definition, indent=1) + "\n")
    OUT_HDR.write_text(
        "/* Generated by scripts/gen_via_def.py from crush80.dts. Do not edit. */\n\n"
        "#ifndef VIA_DEF_H\n#define VIA_DEF_H\n\n"
        f"#define VIA_MATRIX_ROWS {rows}\n#define VIA_MATRIX_COLS {cols}\n\n"
        "#endif /* VIA_DEF_H */\n"
    )
    print(f"{len(keys)} keys, {len(definition['customKeycodes'])} custom keycodes")


if __name__ == "__main__":
    main()
